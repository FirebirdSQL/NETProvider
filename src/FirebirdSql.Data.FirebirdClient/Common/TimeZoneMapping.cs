	const int OffsetBase = 24 * 60 - 1;

	public static bool TryGetByName(string name, out ushort id) => NameToId.TryGetValue(name, out id);

	public static bool TryGetById(ushort id, out string name) => IdToName.TryGetValue(id, out name);

	public static string Normalize(string name)
	{
		if (string.IsNullOrWhiteSpace(name))
			return name;
		if (NameToId.TryGetValue(name, out var id))
			return IdToName[id];
		if (TryParseOffset(name, out var offset))
			return IdToName[(ushort)(OffsetBase + offset)];
		return name;
	}

	[GeneratedRegex(@"^\s*(?<sign>[+-])\s*(?<hours>[0-9]+)\s*(?::\s*(?<minutes>[0-9]+)\s*)?\z", RegexOptions.CultureInvariant)]
	private static partial Regex OffsetRegex();

	static bool TryParseOffset(string name, out int offset)
	{
		offset = 0;
		var m = OffsetRegex().Match(name);
		if (!m.Success)
			return false;
		if (!int.TryParse(m.Groups["hours"].ValueSpan, NumberStyles.None, CultureInfo.InvariantCulture, out var hours))
			return false;
		var minutes = 0;
		if (m.Groups["minutes"].Success && !int.TryParse(m.Groups["minutes"].ValueSpan, NumberStyles.None, CultureInfo.InvariantCulture, out minutes))
			return false;
		if (minutes > 59 || hours > 14 || (hours == 14 && minutes != 0))
			return false;
		offset = m.Groups["sign"].ValueSpan[0] == '-' ? -(hours * 60 + minutes) : hours * 60 + minutes;
		return true;
	}
